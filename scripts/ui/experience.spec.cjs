async function call(route, body, token, method) {
    const result = await fetch(origin + route, {method: method || (body === undefined ? 'GET' : 'POST'), headers: {...(token ? {Authorization: 'Bearer ' + token} : {}), ...(body === undefined ? {} : {'Content-Type': 'application/json', 'Idempotency-Key': randomUUID()})}, body: body === undefined ? undefined : JSON.stringify(body)});
    const value = await result.json(); assert.ok(result.ok, JSON.stringify(value)); return value;
}
