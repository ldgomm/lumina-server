test('la matriz impide ver, solicitar o aprobar áreas sin permiso y aplica cambios en la misma sesión',async t=>{
  const world = await portal(t);
  const admin = await agency(world);
  const {client,id} = await owner(world,'Negocio de accesos','5');
  await admin.post(selected('/businesses/verify',id));
  const member = await colleague(world,client,{name:'Equipo redes',document:'1721663555','TIKTOK.VIEW':'yes','INSTAGRAM.VIEW':'yes','INSTAGRAM.REQUEST':'yes'});
  assert.equal((await member.session.get('/plans')).status,403);
  assert.equal((await member.session.get('/maps')).status,403);
  assert.equal((await member.session.get('/team')).status,403);
  assert.equal((await member.session.post('/requests',{...reviewData,channel:'TIKTOK',service:'VIDEO'})).status,403);
  assert.equal((await member.session.post('/requests',{...reviewData,channel:'YOUTUBE',service:'VIDEO'})).status,403);
  assert.equal((await member.session.post('/requests',reviewData)).status,303);
  const report = await member.session.get('/reports');
  assert.match(report.body,/TikTok/);
  assert.doesNotMatch(report.body,/>YouTube</);
  const current = world.db.get('SELECT revision FROM accounts WHERE id=?',member.id).revision;
  assert.equal((await client.post('/team/'+member.id+'/permissions',{revision:String(current),'TIKTOK.VIEW':'yes'})).status,303);
  assert.equal((await member.session.get('/requests?channel=INSTAGRAM')).status,403);
  assert.equal((await client.post('/team/'+member.id+'/disable',{revision:teamRevision(world,member.id),confirm:'yes'})).status,303);
  assert.equal((await member.session.get('/home')).status,303);
});
test('Google Maps conserva mediciones por ubicación y referencias de reseñas',async t=>{
  const world = await portal(t);
  const admin = await agency(world);
  const {client,id} = await owner(world,'Negocio de Maps','6');
  assert.equal((await admin.post(selected('/maps/location',id),{name:'Sucursal centro',url:'https://maps.example.test/centro'})).status,303);
  const loc = world.db.get('SELECT id FROM maps_locations WHERE company_id=?',id);
  assert.equal((await admin.post(selected('/maps/measurement',id),{location:loc.id,observed:date(4),count:'22',rating:'4,98'})).status,303);
  assert.equal((await admin.post(selected('/maps/measurement',id),{location:loc.id,observed:date(3),count:'23',rating:'4.99'})).status,303);
  const review = {location:loc.id,date:oldDate(3),reference:'review-1',stars:'5',summary:'Atención en caja'};
  assert.equal((await admin.post(selected('/maps/review',id),{...review,status:'DRAFT',response:'Muchas gracias'})).status,303);
  assert.equal((await admin.post(selected('/maps/review',id),{...review,status:'ANSWERED',response:'Gracias por la visita'})).status,303);
  assert.equal(world.db.get('SELECT count(*) AS n FROM maps_reviews').n,1);
  const response = await client.get('/maps');
  assert.match(response.body,/4\.99 \/ 5/);
  assert.match(response.body,/Gracias por la visita/);
  assert.equal((await client.post('/maps/measurement',{location:loc.id,observed:date(2),count:'25',rating:'5'})).status,403);
});
