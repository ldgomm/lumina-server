const oldDate = days => localDay(new Date(Date.now()-days*86400000));
const date = (days,time='10:00') => oldDate(days)+'T'+time;
const selected= (path,id)=>'/agency'+path+'?company='+id;
const reviewData = {title:'Campaña de noviembre',channel:'INSTAGRAM',service:'REEL',quantity:'2',type:'CONTENT',brief:'Piezas para el restaurante'};
const redirectId = response => response.location.split('?')[0].split('/').at(-1);

test('registro, cortesía idempotente, privacidad de cédula y credencial',async t=>{
  const world = await portal(t);
  const { client,id } = await owner(world,'Negocio de bienvenida','1');
  const intro = await client.get('/home');
  assert.match(intro.body,/Tu video de cortesía/);
  const company = world.db.get('SELECT * FROM companies WHERE id=?',id);
  assert.equal(company.document_hint,'9844');
  assert.equal(company.registration_key.length,64);
  assert.doesNotMatch(intro.body,/1748639844/);
  assert.ok(!world.db.get("SELECT password FROM accounts WHERE company_id=?",id).password.includes(password));
  const data = {...reviewData,type:'COURTESY',quantity:'10'};
  const results = await Promise.all([client.post('/requests',data),client.post('/requests',data)]);
  assert.ok(results.every(result=>result.status===303));
  assert.equal(results[0].location,results[1].location);
  assert.equal(world.db.get("SELECT quantity FROM requests WHERE company_id=? AND type='COURTESY'",id).quantity,1);
  const session = world.session();
  const duplicate = await session.post('/register',{company:'Negocio de Bienvenida',name:'Otro',document:'1706707138',ruc:company.ruc,
    phone:'0991234567',password,consent:'yes'});
  assert.equal(duplicate.status,409);
  assert.equal((await client.post('/requests',data,{headers:{Origin:'https://example.test'}})).status,403);
  assert.equal((await client.post('/requests',{...data,_csrf:'incorrecto'})).status,403);
  const another = world.session();
  assert.equal((await another.post('/login',{document:'1748639844',password})).status,303);
  const changed = await client.post('/account/password',{current:password,password:'Otra contraseña larga 1!',confirmation:'Otra contraseña larga 1!'});
  assert.equal(changed.status,303);
  assert.equal((await another.get('/home')).status,303);
});
test('una solicitud conserva fecha, visita, evidencia, aprobación y estadísticas por plataforma',async t=>{
  const world = await portal(t);
  const admin = await agency(world);
  const {client,id} = await owner(world,'Producción de prueba','2');
  const response = await client.post('/requests',reviewData);
  assert.equal(response.status,303);
  const path = response.location;
  const requestId = redirectId(response);
  assert.equal((await admin.post(selected(path+'/state',id),{status:'APPROVED'})).status,409);
  assert.equal((await admin.post(selected('/businesses/verify',id))).status,303);
  assert.equal((await admin.post(selected(path+'/state',id),{status:'APPROVED'})).status,303);
  assert.equal((await admin.post(selected(path+'/visits',id),{starts:date(10),place:'Local',notes:'Grabar en terraza'})).status,303);
  const visit = world.db.get('SELECT id,starts_at FROM visits WHERE request_id=?',requestId);
  assert.match(visit.starts_at,/T15:00:00/);
  assert.equal((await admin.post(selected(path+'/visits/close',id),{status:'DONE',visit:visit.id,recorded:date(10,'10:20'),notes:'Listo'})).status,303);
  assert.equal((await admin.post(selected(path+'/pieces',id),{title:'Reel terraza'})).status,303);
  const piece = world.db.get('SELECT * FROM pieces WHERE request_id=?',requestId);
  const piecePath = path+'/pieces/'+piece.id;
  assert.equal((await admin.post(selected(piecePath+'/evidence',id),{label:'Video de revisión',url:'https://example.test/material'})).status,303);
  assert.equal((await admin.post(selected(piecePath+'/evidence',id),{label:'Inválido',url:'javascript:alert(1)'})).status,400);
  assert.equal((await admin.post(selected(piecePath+'/edit',id),{revision:'2',status:'REVIEW',recorded:date(10,'10:20'),notes:'Grabado con luz natural'})).status,303);
  const view = await client.get(path);
  assert.match(view.body,/Grabado con luz natural/);
  assert.match(view.body,/Video de revisión/);
  assert.equal((await client.post(piecePath+'/review',{revision:'3',status:'APPROVED'})).status,303);
  assert.equal((await admin.post(selected(piecePath+'/edit',id),{revision:'4',status:'DELIVERED',recorded:date(10,'10:20'),notes:'Entregado'})).status,303);
  assert.equal((await admin.post(selected(piecePath+'/publication',id),{channel:'INSTAGRAM',url:'https://example.test/post/1',published:date(9)})).status,303);
  const pub = world.db.get('SELECT id FROM publications WHERE piece_id=?',piece.id);
  assert.equal((await admin.post(selected(piecePath+'/measure',id),{publication:pub.id,observed:date(8),views:'20',likes:'0'})).status,303);
  assert.equal((await admin.post(selected(piecePath+'/measure',id),{publication:pub.id,observed:date(2),views:'30',likes:'5',comments:'0'})).status,303);
  assert.equal((await admin.post(selected(piecePath+'/measure',id),{publication:pub.id,observed:date(2),views:'35'})).status,409);
  const report = await client.get('/reports?from='+oldDate(5)+'&to='+oldDate(0));
  assert.equal(report.status,200);
  assert.match(report.body,/\+10[\s\S]*1 comparadas/);
  assert.match(report.body,/\+5<br><small>1 comparadas · sin base para porcentaje/);
  assert.match(report.body,/Fuente manual/);
  const {client:other} = await owner(world,'Otro negocio','3');
  assert.equal((await other.get(path+'?company='+id)).status,404);
  assert.doesNotMatch((await other.get('/requests?company='+id)).body,/Campaña de noviembre/);
});
