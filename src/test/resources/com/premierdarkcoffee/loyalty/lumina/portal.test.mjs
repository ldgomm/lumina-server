import assert from 'node:assert/strict';
import { test } from 'node:test';
import { localDay, nextMonth } from '../../../../../../main/resources/com/premierdarkcoffee/loyalty/lumina/shared/domain.mjs';
import { agency, colleague, owner, password, portal } from './helpers.mjs';

const oldDate = days => localDay(new Date(Date.now()-days*86400000));
const date = (days,time='10:00') => oldDate(days)+'T'+time;
const selected = (path,id) => path+'?empresa='+id;
const reviewData = {title:'Campaña de noviembre',channel:'INSTAGRAM',service:'REEL',quantity:'2',type:'CONTENT',brief:'Piezas para el restaurante'};
const redirectId = response => response.location.split('?')[0].split('/').at(-1);

test('registro, cortesía idempotente, privacidad de cédula y credencial',async t=>{
  const world = await portal(t);
  const { client,id } = await owner(world,'Negocio de bienvenida','1');
  const intro = await client.get('/inicio');
  assert.match(intro.body,/Tu video de cortesía/);
  const company = world.db.get('SELECT * FROM companies WHERE id=?',id);
  assert.equal(company.document_hint,'7891');
  assert.equal(company.registration_key.length,64);
  assert.ok(!JSON.stringify(company).includes('1234567891'));
  assert.ok(!world.db.get("SELECT password FROM accounts WHERE company_id=?",id).password.includes(password));
  const data = {...reviewData,type:'COURTESY',quantity:'10'};
  const results = await Promise.all([client.post('/solicitudes',data),client.post('/solicitudes',data)]);
  assert.ok(results.every(result=>result.status===303));
  assert.equal(results[0].location,results[1].location);
  assert.equal(world.db.get("SELECT quantity FROM requests WHERE company_id=? AND type='COURTESY'",id).quantity,1);
  const session = world.session();
  const duplicate = await session.post('/registro',{company:'Negocio de Bienvenida',name:'Otro',document:'1234567891',
    phone:'0991234567',email:'otro@example.test',password,consent:'yes'});
  assert.equal(duplicate.status,409);
  assert.equal((await client.post('/solicitudes',data,{headers:{Origin:'https://example.test'}})).status,403);
  assert.equal((await client.post('/solicitudes',{...data,_csrf:'incorrecto'})).status,403);
  const another = world.session();
  assert.equal((await another.post('/entrar',{email:'negocio1@example.test',password})).status,303);
  const changed = await client.post('/cuenta/clave',{current:password,password:'Otra contraseña larga 1!'});
  assert.equal(changed.status,303);
  assert.equal((await another.get('/inicio')).status,303);
});
test('una solicitud conserva fecha, visita, evidencia, aprobación y estadísticas por plataforma',async t=>{
  const world = await portal(t);
  const admin = await agency(world);
  const {client,id} = await owner(world,'Producción de prueba','2');
  const response = await client.post('/solicitudes',reviewData);
  assert.equal(response.status,303);
  const path = response.location;
  const requestId = redirectId(response);
  assert.equal((await admin.post(selected(path+'/estado',id),{status:'APPROVED'})).status,409);
  assert.equal((await admin.post(selected('/clientes/verificar',id))).status,303);
  assert.equal((await admin.post(selected(path+'/estado',id),{status:'APPROVED'})).status,303);
  assert.equal((await admin.post(selected(path+'/visitas',id),{starts:date(10),place:'Local',notes:'Grabar en terraza'})).status,303);
  const visit = world.db.get('SELECT id,starts_at FROM visits WHERE request_id=?',requestId);
  assert.match(visit.starts_at,/T15:00:00/);
  assert.equal((await admin.post(selected(path+'/visitas/cerrar',id),{status:'DONE',visit:visit.id,recorded:date(10,'10:20'),notes:'Listo'})).status,303);
  assert.equal((await admin.post(selected(path+'/piezas',id),{title:'Reel terraza'})).status,303);
  const piece = world.db.get('SELECT * FROM pieces WHERE request_id=?',requestId);
  const piecePath = path+'/piezas/'+piece.id;
  assert.equal((await admin.post(selected(piecePath+'/evidencia',id),{label:'Video de revisión',url:'https://example.test/material'})).status,303);
  assert.equal((await admin.post(selected(piecePath+'/evidencia',id),{label:'Inválido',url:'javascript:alert(1)'})).status,400);
  assert.equal((await admin.post(selected(piecePath+'/editar',id),{revision:'1',status:'REVIEW',recorded:date(10,'10:20'),notes:'Grabado con luz natural'})).status,303);
  const view = await client.get(path);
  assert.match(view.body,/Grabado con luz natural/);
  assert.match(view.body,/Video de revisión/);
  assert.equal((await client.post(piecePath+'/revisar',{revision:'2',status:'APPROVED'})).status,303);
  assert.equal((await admin.post(selected(piecePath+'/editar',id),{revision:'3',status:'DELIVERED',recorded:date(10,'10:20'),notes:'Entregado'})).status,303);
  assert.equal((await admin.post(selected(piecePath+'/publicacion',id),{channel:'INSTAGRAM',url:'https://example.test/post/1',published:date(9)})).status,303);
  const pub = world.db.get('SELECT id FROM publications WHERE piece_id=?',piece.id);
  assert.equal((await admin.post(selected(piecePath+'/medir',id),{publication:pub.id,observed:date(8),views:'20',likes:'0'})).status,303);
  assert.equal((await admin.post(selected(piecePath+'/medir',id),{publication:pub.id,observed:date(2),views:'30',likes:'5',comments:'0'})).status,303);
  assert.equal((await admin.post(selected(piecePath+'/medir',id),{publication:pub.id,observed:date(2),views:'35'})).status,409);
  const report = await client.get('/reportes?desde='+oldDate(5)+'&hasta='+oldDate(0));
  assert.equal(report.status,200);
  assert.match(report.body,/\+10 · 1 comparadas/);
  assert.match(report.body,/\+5 · 1 comparadas/);
  assert.match(report.body,/Fuente manual/);
  const {client:other} = await owner(world,'Otro negocio','3');
  assert.equal((await other.get(path+'?empresa='+id)).status,404);
  assert.doesNotMatch((await other.get('/solicitudes?empresa='+id)).body,/Campaña de noviembre/);
});
test('membresía Premium y paquete individual mantienen precio, cupos y cotización',async t=>{
  const world = await portal(t);
  const admin = await agency(world);
  const {client,id} = await owner(world,'Negocio de planes','4');
  await admin.post(selected('/clientes/verificar',id));
  assert.equal(nextMonth('2028-01-31'),'2028-02-29');
  assert.equal((await admin.post('/planes',{name:'Premium',term:'MONTHLY',price:'375.25',wallet:'GIFT',REEL:'1',WEB:'1'})).status,303);
  assert.equal((await admin.post('/planes',{name:'Solo stories',term:'ONE_OFF',price:'',wallet:'NONE',STORY:'3'})).status,303);
  const plan = world.db.get("SELECT id FROM plans WHERE name='Premium'").id;
  const single = world.db.get("SELECT id FROM plans WHERE name='Solo stories'").id;
  const request = await client.post('/solicitudes',{type:'PLAN',plan});
  assert.equal(request.status,303);
  assert.equal((await admin.post(selected(request.location+'/estado',id),{status:'APPROVED'})).status,303);
  assert.equal((await admin.post(selected('/planes/activar',id),{plan,startsOn:oldDate(1),requestId:redirectId(request)})).status,303);
  const contract = world.db.get('SELECT * FROM contracts WHERE company_id=?',id);
  assert.equal(contract.agreed_minor,37525);
  assert.equal((await admin.post(selected('/planes/activar',id),{plan,startsOn:oldDate(1)})).status,409);
  const pieceRequest = await client.post('/solicitudes',reviewData);
  await admin.post(selected(pieceRequest.location+'/estado',id),{status:'APPROVED'});
  assert.equal((await admin.post(selected(pieceRequest.location+'/piezas',id),{title:'Cupo 1',contract:contract.id})).status,303);
  assert.equal((await admin.post(selected(pieceRequest.location+'/piezas',id),{title:'Cupo duplicado',contract:contract.id})).status,409);
  assert.match((await client.get('/planes')).body,/Wallet de cortesía/);
  const oneOff = await client.post('/solicitudes',{type:'PLAN',plan:single});
  assert.equal((await admin.post(selected(oneOff.location+'/estado',id),{status:'APPROVED'})).status,409);
  assert.equal((await admin.post(selected(oneOff.location+'/cotizar',id),{amount:'42,55',terms:'Incluye tres stories.'})).status,303);
  const q = world.db.get("SELECT id FROM quotes WHERE request_id=? AND status='OFFERED'",redirectId(oneOff));
  assert.equal((await client.post(oneOff.location+'/aceptar',{quote:q.id})).status,303);
  const end = nextMonth(oldDate(0));
  assert.equal((await admin.post(selected('/planes/activar',id),{plan:single,startsOn:oldDate(0),endsBefore:end,
    requestId:redirectId(oneOff),agreed:'1'})).status,303);
  assert.equal(world.db.get('SELECT agreed_minor FROM contracts WHERE plan_id=?',single).agreed_minor,4255);
});
test('la matriz impide ver, solicitar o aprobar áreas sin permiso y aplica cambios en la misma sesión',async t=>{
  const world = await portal(t);
  const admin = await agency(world);
  const {client,id} = await owner(world,'Negocio de accesos','5');
  await admin.post(selected('/clientes/verificar',id));
  const member = await colleague(world,client,{name:'Equipo redes',email:'equipo@example.test','TIKTOK.VIEW':'yes','INSTAGRAM.VIEW':'yes','INSTAGRAM.REQUEST':'yes'});
  assert.equal((await member.session.get('/planes')).status,403);
  assert.equal((await member.session.get('/mapas')).status,403);
  assert.equal((await member.session.get('/equipo')).status,403);
  assert.equal((await member.session.post('/solicitudes',{...reviewData,channel:'TIKTOK',service:'VIDEO'})).status,403);
  assert.equal((await member.session.post('/solicitudes',{...reviewData,channel:'YOUTUBE',service:'VIDEO'})).status,403);
  assert.equal((await member.session.post('/solicitudes',reviewData)).status,303);
  const report = await member.session.get('/reportes');
  assert.match(report.body,/TikTok/);
  assert.doesNotMatch(report.body,/>YouTube</);
  const current = world.db.get('SELECT revision FROM accounts WHERE id=?',member.id).revision;
  assert.equal((await client.post('/equipo/'+member.id+'/permisos',{revision:String(current),'TIKTOK.VIEW':'yes'})).status,303);
  assert.equal((await member.session.get('/solicitudes?canal=INSTAGRAM')).status,403);
  assert.equal((await client.post('/equipo/'+member.id+'/desactivar',{confirm:'yes'})).status,303);
  assert.equal((await member.session.get('/inicio')).status,303);
});
test('Google Maps conserva mediciones por ubicación y referencias de reseñas',async t=>{
  const world = await portal(t);
  const admin = await agency(world);
  const {client,id} = await owner(world,'Negocio de Maps','6');
  assert.equal((await admin.post(selected('/mapas/ubicacion',id),{name:'Sucursal centro',url:'https://maps.example.test/centro'})).status,303);
  const loc = world.db.get('SELECT id FROM maps_locations WHERE company_id=?',id);
  assert.equal((await admin.post(selected('/mapas/medicion',id),{location:loc.id,observed:date(4),count:'22',rating:'4,98'})).status,303);
  assert.equal((await admin.post(selected('/mapas/medicion',id),{location:loc.id,observed:date(3),count:'23',rating:'4.99'})).status,303);
  const review = {location:loc.id,date:oldDate(3),reference:'review-1',stars:'5',summary:'Atención en caja'};
  assert.equal((await admin.post(selected('/mapas/resena',id),{...review,status:'DRAFT',response:'Muchas gracias'})).status,303);
  assert.equal((await admin.post(selected('/mapas/resena',id),{...review,status:'ANSWERED',response:'Gracias por la visita'})).status,303);
  assert.equal(world.db.get('SELECT count(*) AS n FROM maps_reviews').n,1);
  const response = await client.get('/mapas');
  assert.match(response.body,/4\.99 \/ 5/);
  assert.match(response.body,/Gracias por la visita/);
  assert.equal((await client.post('/mapas/medicion',{location:loc.id,observed:date(2),count:'25',rating:'5'})).status,403);
});
